/**
 * Стадии, на которых срывается оплата, и что делать по каждой.
 *
 * ЗАЧЕМ ЭТОТ ФАЙЛ СУЩЕСТВУЕТ
 * Экран отказов открывают с одной жалобой: «человек заплатил, ничего не
 * пришло». Красная строка со словом `provision_failed` на неё не
 * отвечает. Отвечают три вещи: на каком шаге всё встало, ушли ли деньги и
 * что теперь сделать руками. Первое и третье лежат здесь, второе приходит
 * с сервера отдельными полями (purchase_status, subscription_*).
 *
 * ПУТЬ ПЛАТЕЖА — ЧЕТЫРЕ ШАГА. Отказ всегда случается на одном из них:
 *
 *   1. приём вебхука      провайдер постучался, мы его поняли;
 *   2. проверка платежа   подпись, сумма, повторность;
 *   3. запись денег       покупка отмечена оплаченной;
 *   4. выдача доступа     подписка и ключ у человека.
 *
 * Чем позже шаг, тем вероятнее, что деньги списаны, а товара нет — и тем
 * срочнее ручное вмешательство. На первом шаге денег обычно ещё нет.
 *
 * КАК ДОБАВЛЯТЬ СТАДИЮ. Появилась новая строка stage в коде (см.
 * database.log_payment_error) — добавьте её сюда. Незнакомая стадия не
 * ломает экран: она покажется своим техническим именем с честной
 * подписью «шаг неизвестен», но разбирать её придётся по тексту ошибки.
 */

