export function stageMeta(stage: string): StageMeta {
  return (
    STAGES[stage] ?? {
      label: stage || "Стадия не указана",
      step: 3,
      what: "Такой стадии в справочнике нет — она появилась в коде позже этого экрана.",
      next: "Разбирайте по тексту ошибки ниже и добавьте стадию в components/payments/stages.ts.",
    }
  );
}

/** Есть ли стадия в справочнике. Нужно, чтобы не врать про шаг. */
export function isKnownStage(stage: string): boolean {
  return Boolean(STAGES[stage]);
}

/**
 * Исход отказа: ушли ли деньги и остался ли человек без доступа.
 *
 * Считается по состоянию покупки и подписки на момент просмотра, а не по
 * самой ошибке: половина записей в этом журнале — попытки, после которых
 * человек оплатил со второго раза, и звать админа по ним незачем.
 */
export interface Outcome {
  kind: StatusKind;
  /** Итог одной фразой — то, что стоит в строке таблицы. */
  title: string;
  /** Развёрнуто: что это значит для человека и денег. */
  detail: string;
  /** Требуется ли ручная работа. По этому полю строка подсвечивается. */
  needsHands: boolean;
}

export function outcomeOf(row: PaymentErrorRow): Outcome {
  const hasAccess =
    row.subscription_status === "active" &&
    row.subscription_expires_at !== null &&
    new Date(row.subscription_expires_at).getTime() > Date.now();

  if (row.purchase_status === "paid") {
    return {
      kind: "success",
      title: "Покупка всё-таки прошла",
      detail: hasAccess
        ? "Оплата засчитана, доступ у человека есть. Ошибка была на промежуточной попытке — делать ничего не нужно."
        : "Оплата засчитана, но действующей подписки не видно. Проверьте карточку: возможно, доступ не выдан или уже истёк.",
      needsHands: !hasAccess,
    };
  }

  if (row.purchase_status === "pending") {
    return {
      kind: "risk",
      title: "Деньги могли уйти, покупка висит",
      detail:
        "Счёт до сих пор не переведён в оплаченный. Если у провайдера платёж прошёл — доступ надо выдать руками, оплату повторять не нужно.",
      needsHands: true,
    };
  }

  if (row.purchase_status === "expired") {
    return {
      kind: "neutral",
      title: "Счёт истёк, оплаты не было",
      detail:
        "Человек не довёл оплату до конца. Если он утверждает обратное — ищите платёж в кабинете провайдера по сумме и времени.",
      needsHands: false,
    };
  }

  // purchase_id пуст или строки с таким номером нет: отказ случился до
  // того, как уведомление связали с конкретной покупкой.
  return {
    kind: "pending",
    title: "До покупки не дошло",
    detail:
      "Уведомление не связалось ни с одним счётом — отказ на входе. Деньги, скорее всего, не списаны; проверять надо в кабинете провайдера.",
    needsHands: false,
  };
}
