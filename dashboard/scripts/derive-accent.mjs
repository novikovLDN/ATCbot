#!/usr/bin/env node
/**
 * Как получены ступени акцентной шкалы, которых нет в исследовании.
 *
 * В research-2026.md §10.3 для кобальта заданы только ступени 9, 10 и 11.
 * Остальные восемь нужны на практике: подложка «выбрано» (3), её hover (4),
 * pressed (5), границы (6–7), focus-ring (8), тёмный текст на подложке (12).
 * Этот скрипт считает их по той же модели, что и вся палитра исследования:
 * фиксированный тон OKLCH 264, светлота и хрома идут по ровной кривой.
 *
 * Скрипт ничего не переписывает — он печатает hex, который вручную кладётся в
 * src/styles/tokens.css. Так значения остаются читаемыми в диффе, а сборка не
 * зависит от генератора.
 *
 * Запуск: node scripts/derive-accent.mjs
 */

/** OKLCH → sRGB. Формулы Björn Ottosson (oklab), без клиппинга по гамуту:
 *  значения ниже подобраны так, чтобы в sRGB попадать без обрезки. */
export function oklchToRgb(L, C, hDeg) {
  const h = (hDeg * Math.PI) / 180;
  const a = C * Math.cos(h);
  const b = C * Math.sin(h);
  const l_ = L + 0.3963377774 * a + 0.2158037573 * b;
  const m_ = L - 0.1055613458 * a - 0.0638541728 * b;
  const s_ = L - 0.0894841775 * a - 1.291485548 * b;
  const l = l_ ** 3;
  const m = m_ ** 3;
  const s = s_ ** 3;
  const lr = 4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s;
  const lg = -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s;
  const lb = -0.0041960863 * l - 0.7034186147 * m + 1.707614701 * s;
  const enc = (x) => {
    const v = x <= 0.0031308 ? 12.92 * x : 1.055 * Math.pow(Math.max(x, 0), 1 / 2.4) - 0.055;
    return Math.round(Math.min(1, Math.max(0, v)) * 255);
  };
  return [enc(lr), enc(lg), enc(lb)];
}

const HUE = 264;
// [светлота, хрома] по ступеням 1…12.
const LIGHT = [
  [0.991, 0.004], [0.98, 0.008], [0.962, 0.018], [0.94, 0.03],
  [0.918, 0.042], [0.888, 0.058], [0.84, 0.085],
  [0.63, 0.15],   // 8 — focus-ring, темнее «радиксовой» ради 3:1 к фону
  [0.52, 0.18], [0.48, 0.176], [0.455, 0.17], [0.28, 0.09],
];
const DARK = [
  [0.17, 0.012], [0.2, 0.016], [0.245, 0.038], [0.275, 0.052],
  [0.305, 0.064], [0.35, 0.082], [0.41, 0.11],
  [0.6, 0.16],    // 8 — focus-ring на тёмном
  [0.58, 0.182],
  [0.55, 0.182],  // 10 — hover темнее 9: белый текст на более светлом не добирает 4.5:1
  [0.78, 0.11], [0.92, 0.05],
];

const hex = (rgb) => "#" + rgb.map((v) => v.toString(16).padStart(2, "0").toUpperCase()).join("");

if (import.meta.url === `file://${process.argv[1]}`) {
  for (const [name, scale] of [["светлая", LIGHT], ["тёмная", DARK]]) {
    console.log(`\n${name} тема, тон ${HUE}:`);
    scale.forEach(([L, C], i) => {
      const rgb = oklchToRgb(L, C, HUE);
      console.log(
        `  a${String(i + 1).padStart(2)}  ${hex(rgb)}  rgb ${rgb.join(" ")}  oklch(${(L * 100).toFixed(1)}% ${C.toFixed(3)} ${HUE})`,
      );
    });
  }
}
