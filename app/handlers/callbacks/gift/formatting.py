"""Подарки: как называть тариф и период в текстах.

ЧТО ЗДЕСЬ
    Две функции подписи. Их зовут все экраны подарка — мастер покупки,
    список «Мои подарки» и карточка подарка.

ПОЧЕМУ ВЫДЕЛЕНО
    Иначе список подарков пришлось бы импортировать из мастера покупки
    ради двух строк — и получить кольцо импортов на ровном месте.

ЧТО ЛЕГКО СЛОМАТЬ
    Русские окончания периода («месяц / месяца / месяцев») считаются по
    числу месяцев. Правка здесь меняет текст сразу в трёх местах, включая
    описание платежа, которое видит платёжный провайдер.
"""


def _tariff_display_name(tariff: str) -> str:
    """Человекочитаемое название тарифа."""
    names = {"basic": "Basic", "plus": "Plus", "combo_basic": "Комбо Basic", "combo_plus": "Комбо Plus"}
    return names.get(tariff, tariff.capitalize())


def _period_display(period_days: int) -> str:
    """Человекочитаемый период."""
    months = period_days // 30
    if months == 1:
        return "1 месяц"
    elif months in (2, 3, 4):
        return f"{months} месяца"
    else:
        return f"{months} месяцев"
