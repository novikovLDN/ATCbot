"""Единое правило стартовой задержки фоновых воркеров.

ЗАЧЕМ. Все воркеры поднимаются в main.py одной пачкой, в пределах пары
миллисекунд. Если каждый ждёт фиксированную паузу, они и дальше идут строем:
через минуту после старта процесса разом просыпаются напоминания, ферма и
монитор трафика — каждый берёт соединения из пула и начинает слать сообщения
в Telegram. Пик приходится ровно на прогрев бота, когда пул ещё не разогнан,
а вебхук уже принимает апдейты. Хуже того, периоды воркеров кратны друг другу
(45 / 30 / 5 минут), поэтому раз в полтора часа фазы совпадают снова.

Случайная задержка разносит старты по минутному окну и разрывает эту
кратность: дальше воркеры расходятся по фазе и больше не сходятся.

ПОЧЕМУ ОТДЕЛЬНЫЙ МОДУЛЬ. Раньше эти три строки копировались в каждый воркер,
и половина копий разъехалась: часть файлов делала random.uniform(5, 60),
часть — asyncio.sleep(60) или sleep(30). Правило, живущее в одном месте,
невозможно забыть при добавлении нового воркера.
"""
import asyncio
import logging
import random

logger = logging.getLogger(__name__)

# Окно разброса. Нижняя граница не нулевая специально: первым делом после
# старта процесса идёт регистрация вебхука и прогрев пула, лезть туда с
# фоновой работой в первые секунды незачем.
STARTUP_JITTER_MIN_SECONDS = 5.0
STARTUP_JITTER_MAX_SECONDS = 60.0


async def startup_jitter(worker_name: str) -> float:
    """Подождать случайное время перед первой итерацией воркера.

    Возвращает фактическую задержку — удобно для логов и тестов.
    """
    delay = random.uniform(STARTUP_JITTER_MIN_SECONDS, STARTUP_JITTER_MAX_SECONDS)
    await asyncio.sleep(delay)
    logger.debug("%s: startup jitter done (%.1fs)", worker_name, delay)
    return delay
