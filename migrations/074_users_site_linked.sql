-- Migration 074: users.site_linked — привязан ли аккаунт на сайте QoDev.
--
-- Зачем. Колонку читают два места: воркер синхронизации
-- (app/workers/site_sync_worker.py, `WHERE u.site_linked = TRUE`) и
-- админский экран связок. Читают без всякой защиты — если колонки нет,
-- запрос падает.
--
-- Откуда она бралась раньше. Её создавали прямо на горячем пути:
-- `ALTER TABLE users ADD COLUMN IF NOT EXISTS site_linked ...` выполнялся
-- внутри обработчика /start на каждой привязке сайта, и второй раз — при
-- открытии админского экрана. То есть схема правилась в момент, когда
-- человек нажимает кнопку.
--
-- Почему так нельзя. ALTER TABLE берёт ACCESS EXCLUSIVE: он ждёт
-- завершения всех текущих запросов к users и всё это время не пускает
-- новые. Любой /start, любое чтение профиля, любая покупка встают в
-- очередь. Длительность паузы задаёт не тот, кто привязывает сайт, а
-- самый долгий чужой запрос в этот момент. `IF NOT EXISTS` здесь не
-- помогает: проверка идёт уже под взятой блокировкой, и «ничего не
-- делать» стоит ровно столько же.
--
-- Миграция аддитивная и идемпотентная: на боевой базе колонка уже
-- создана обработчиком, ADD COLUMN IF NOT EXISTS просто ничего не сделает.

ALTER TABLE users ADD COLUMN IF NOT EXISTS site_linked BOOLEAN DEFAULT FALSE;
