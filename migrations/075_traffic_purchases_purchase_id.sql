-- Migration 075: traffic_purchases.purchase_id — ключ идемпотентности
-- начисления комбо-гигабайтов.
--
-- Зачем. add_bypass_traffic не идемпотентна: она ПРИБАВЛЯЕТ трафик к
-- текущему лимиту в панели. Пока отказ начисления не доводился до 5xx,
-- второго вызова просто не случалось — оплаченные гигабайты терялись
-- насовсем, и это видно по жалобам. Теперь отказ обязан приводить к
-- повтору вебхука, а повтор без ключа выдал бы второй пакет — и вот это
-- не увидит никто: лишние гигабайты в поддержку не приносят.
--
-- Форма ключа. Колонка в уже существующей таблице учёта покупок трафика,
-- а не отдельная таблица отметок: строка «начислено N ГБ» и признак «за
-- эту покупку начислено» — одно и то же событие. Разнести их по двум
-- таблицам значит завести два источника правды, которые разъедутся при
-- первом же сбое между двумя записями.
--
-- Уникальность частичная. purchase_id остаётся NULL у покупок пакетов ГБ
-- и bypass-only (у них своего идентификатора покупки нет) и у всех
-- исторических строк — полный UNIQUE их бы не пропустил, потому что NULL
-- в Postgres уникальности не нарушают, но частичный индекс ещё и меньше.
--
-- Идемпотентность. ADD COLUMN IF NOT EXISTS + CREATE UNIQUE INDEX IF NOT
-- EXISTS: на боевой базе, где traffic_purchases живёт с миграции 038,
-- миграция проедет вхолостую, а уникальный индекс построится без единого
-- конфликта — у всех прошлых строк purchase_id IS NULL.

ALTER TABLE traffic_purchases ADD COLUMN IF NOT EXISTS purchase_id TEXT;

CREATE UNIQUE INDEX IF NOT EXISTS idx_traffic_purchases_purchase_id
    ON traffic_purchases (purchase_id)
    WHERE purchase_id IS NOT NULL;
