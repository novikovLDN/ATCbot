-- Migration 071: разовый сброс залипших флагов reminder_7d_sent /
-- reminder_1d_sent у действующих подписок.
--
-- Проблема. Колонки добавлены миграцией 036, код выставляет их в TRUE после
-- отправки напоминания (database/reminders_queries.py), а в FALSE не
-- возвращал никто: сброс при продлении в grant_access перечислял только
-- старые флаги (reminder_sent, 3d, 24h, 3h, 6h). Получалось, что напоминание
-- «за 7 дней» и «за сутки» приходило человеку один раз за всю жизнь, а при
-- всех последующих продлениях он оставался без предупреждения об окончании.
--
-- Код уже исправлен (оба флага сбрасываются во всех ветках grant_access), но
-- у текущей базы флаги остались в TRUE — без этого сброса напоминания не
-- заработают до следующего продления.
--
-- Сбрасываем только у тех, чья подписка ещё действует: у истёкших флаг
-- всё равно обнулится при следующей выдаче, а трогать архив незачем.
UPDATE subscriptions
SET reminder_7d_sent = FALSE,
    reminder_1d_sent = FALSE
WHERE (reminder_7d_sent = TRUE OR reminder_1d_sent = TRUE)
  AND expires_at > NOW();
